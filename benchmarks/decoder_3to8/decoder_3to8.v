module decoder_3to8(Y7, Y6, Y5, Y4, Y3, Y2, Y1, Y0, A, B, C, en);
    output Y7, Y6, Y5, Y4, Y3, Y2, Y1, Y0;
    input  A, B, C;
    input  en;
    assign {Y7, Y6, Y5, Y4, Y3, Y2, Y1, Y0} = 
        (!en) ? 8'b1111_1111 :
        ({C, B, A} == 3'b000) ? 8'b1111_1110 :
        ({C, B, A} == 3'b001) ? 8'b1111_1101 :
        ({C, B, A} == 3'b010) ? 8'b1111_1011 :
        ({C, B, A} == 3'b011) ? 8'b1111_0111 :
        ({C, B, A} == 3'b100) ? 8'b1110_1111 :
        ({C, B, A} == 3'b101) ? 8'b1101_1111 :
        ({C, B, A} == 3'b110) ? 8'b1011_1111 :
        ({C, B, A} == 3'b111) ? 8'b0111_1111 :
        8'b1111_1111;
endmodule
